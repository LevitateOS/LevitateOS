//! `cargo xtask gen`: the JSON the tools print is described once, by
//! their Rust output types. This writes the JSON Schemas next to each tool
//! and the TypeScript declarations into every TUI app whose manifest lists the
//! tool (`src/generated/<tool>.ts`), and
//! captures each tool's `--help` for the docs site, so pages show the real
//! options instead of copies. Each variant's facts (identity and distro
//! profile) go into docs-content's `src/distros.ts`, for the docs and the TUIs.

use anyhow::{Context, Result, bail};
use schemars::{JsonSchema, schema_for};
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by `cargo xtask gen` from the tool's Rust output types. Do not edit.\n";

/// Where generated text goes: written when it changed, or (with `check`)
/// only compared.
pub struct Out {
    check: bool,
    stale: Vec<PathBuf>,
    written: usize,
}

impl Out {
    fn emit(&mut self, path: &Path, text: &str) -> Result<()> {
        let current = fs::read_to_string(path).ok();
        if current.as_deref() == Some(text) {
            return Ok(());
        }
        if self.check {
            self.stale.push(path.to_path_buf());
            return Ok(());
        }
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(path, text).with_context(|| format!("writing {}", path.display()))?;
        println!("wrote {}", path.display());
        self.written += 1;
        Ok(())
    }
}

pub fn run(check: bool) -> Result<()> {
    let mut out = Out { check, stale: Vec::new(), written: 0 };
    // The output is formatted with the workspace's oxfmt.
    crate::tasks::check::install_js_workspace(&crate::util::repo::repo_root()?)?;
    generate(&mut out)?;
    if !out.stale.is_empty() {
        for path in &out.stale {
            eprintln!("out of date: {}", path.display());
        }
        bail!("{} generated file(s) are out of date; run cargo xtask gen", out.stale.len());
    }
    if out.written == 0 {
        println!("generated files are current");
    }
    Ok(())
}

fn generate(out: &mut Out) -> Result<()> {
    let root = crate::util::repo::repo_root()?;

    let schemas = root.join("tools/recpart/docs/frontend-handoff/schemas");
    write_schema::<recpart::DiskListResult>(out, &schemas, "list-disks")?;
    write_schema::<recpart::InspectResult>(out, &schemas, "inspect")?;
    write_schema::<recpart::ManualLayout>(out, &schemas, "layout")?;
    write_schema::<recpart::PartitionPlan>(out, &schemas, "plan-result")?;
    write_schema::<recpart::ApplyResult>(out, &schemas, "apply-result")?;
    write_schema::<recpart::types::ErrorPayload>(out, &schemas, "error")?;
    write_schema::<recab::Status>(out, &root.join("tools/recab/docs"), "status")?;
    let install_docs = root.join("tools/recstrap/docs/schemas");
    write_schema::<install_tools::output::StrapEvent>(out, &install_docs, "recstrap-event")?;
    write_schema::<install_tools::output::FstabResult>(out, &install_docs, "recfstab-result")?;
    write_schema::<install_tools::output::ErrorPayload>(out, &install_docs, "error")?;

    let cfg = Config::new().with_large_int("number");
    let mut recpart_ts = Declarations::new(&cfg);
    recpart_ts.types_from::<recpart::DiskListResult>();
    recpart_ts.types_from::<recpart::InspectResult>();
    recpart_ts.types_from::<recpart::ManualLayout>();
    recpart_ts.types_from::<recpart::PartitionPlan>();
    recpart_ts.types_from::<recpart::ApplyResult>();
    recpart_ts.types_from::<recpart::types::ErrorPayload>();
    recpart_ts.constant("PLAN_SCHEMA_VERSION", &recpart::types::PLAN_SCHEMA_VERSION)?;
    recpart_ts.constant("APPLY_SCHEMA_VERSION", &recpart::types::APPLY_SCHEMA_VERSION)?;
    recpart_ts.constant("ERROR_SCHEMA_VERSION", &recpart::types::ERROR_SCHEMA_VERSION)?;
    recpart_ts.constant("DISK_LIST_SCHEMA_VERSION", &recpart::types::DISK_LIST_SCHEMA_VERSION)?;
    recpart_ts.constant("INSPECT_SCHEMA_VERSION", &recpart::types::INSPECT_SCHEMA_VERSION)?;
    recpart_ts.constant("CONFIRM_TOKEN", &recpart::types::CONFIRM_TOKEN)?;
    recpart_ts.value_enum::<recpart::InstallMode>("INSTALL_MODES", "INSTALL_MODE_HELP")?;
    recpart_ts.constant("DEFAULT_INSTALL_MODE", &recpart::InstallMode::default())?;
    recpart_ts.value_enum::<recpart::Role>("ROLES", "ROLE_HELP")?;
    recpart_ts.raw(RECPART_OUTPUT);

    let mut recab_ts = Declarations::new(&cfg);
    recab_ts.types_from::<recab::Status>();
    recab_ts.value_enum::<recab::Slot>("SLOTS", "SLOT_HELP")?;

    let mut recstrap_ts = Declarations::new(&cfg);
    recstrap_ts.types_from::<install_tools::output::StrapEvent>();
    recstrap_ts.types_from::<install_tools::output::FstabResult>();
    recstrap_ts.types_from::<install_tools::output::ErrorPayload>();
    recstrap_ts.constant("STRAP_SCHEMA_VERSION", &install_tools::output::STRAP_SCHEMA_VERSION)?;
    recstrap_ts.constant("FSTAB_SCHEMA_VERSION", &install_tools::output::FSTAB_SCHEMA_VERSION)?;
    recstrap_ts.constant("ERROR_SCHEMA_VERSION", &install_tools::output::ERROR_SCHEMA_VERSION)?;
    recstrap_ts.raw(RECSTRAP_OUTPUT);

    let modules = [("recpart", &recpart_ts), ("recab", &recab_ts), ("recstrap", &recstrap_ts)];
    for app in distro_contract::tui_apps::discover(&root)? {
        for (tool, module) in &modules {
            if app.tools.iter().any(|t| t == tool) {
                module.write(out, &root, &app.dir.join(format!("src/generated/{tool}.ts")))?;
            }
        }
    }

    write_tool_help(out, &root)?;
    write_distros(out, &root)?;
    Ok(())
}

/// One record per variant, as `distro_contract::load` reads it: identity, the names
/// derived from it, and the profile, plus the profile vocabulary and the os-release
/// field each fact is written to on the image.
fn write_distros(out: &mut Out, root: &Path) -> Result<()> {
    use distro_contract::profile::{self, Desktop, InitSystem, KernelLine, Libc, PackageBackend, PrivilegeTool};
    use serde_json::json;

    let mut distros = Vec::new();
    for id in distro_contract::distro_ids(root) {
        let variant = distro_contract::load(root, &id)?;
        let c = &variant.contract;
        let kernel = distro_builder::kernel::pin(&variant)?;
        let privilege = c.profile.privilege;
        distros.push(json!({
            "id": variant.id,
            "osName": c.identity.os_name,
            "osId": c.identity.os_id,
            "osVersion": c.identity.os_version,
            "isoLabel": c.identity.iso_label,
            "defaultHostname": c.identity.default_hostname,
            "loginPrompt": c.identity.login_prompt,
            "isoFile": c.artifacts.release_iso,
            "installedInitramfs": c.artifacts.initramfs_installed,
            "installShell": c.install_ux.shell,
            "kernel": { "version": kernel.version, "localversion": kernel.localversion },
            "profile": c.profile,
            "privilegeTool": {
                "configFile": privilege.config_file(),
                "adminRuleFile": format!("/{}", privilege.admin_rule_file()),
                "adminRule": privilege.admin_rule(),
            },
        }));
    }
    let values = json!({
        "packages": PackageBackend::ALL,
        "init": InitSystem::ALL,
        "libc": Libc::ALL,
        "privilege": PrivilegeTool::ALL,
        "desktop": Desktop::ALL,
        "kernel_line": KernelLine::ALL,
    });
    let fields = json!({
        "packages": profile::REC_PACKAGES,
        "init": profile::REC_INIT,
        "libc": profile::REC_LIBC,
        "privilege": profile::REC_PRIVILEGE,
        "desktop": profile::REC_DESKTOP,
        "kernel_line": profile::REC_KERNEL_LINE,
    });
    let text = format!(
        "// Generated by `cargo xtask gen` from distro/variants/*/distro.toml and distro-profile. Do not edit.\n\n\
         /** Every variant, by id: its identity, the names derived from it, and its distro profile. */\n\
         export const DISTROS = {} as const;\n\n\
         export type Distro = (typeof DISTROS)[number];\n\
         export type DistroId = Distro[\"id\"];\n\n\
         /** The values each profile fact can take. */\n\
         export const PROFILE_VALUES = {} as const;\n\n\
         /** The /etc/os-release field each fact is written to on the image. */\n\
         export const OS_RELEASE_FIELDS = {} as const;\n\n\
         /** The group whose members become root through the privilege tool. */\n\
         export const ADMIN_GROUP = {} as const;\n\n\
         export type Profile = {{ -readonly [K in keyof typeof PROFILE_VALUES]: (typeof PROFILE_VALUES)[K][number] }};\n\n\
         {}",
        serde_json::to_string_pretty(&distros)?,
        serde_json::to_string_pretty(&values)?,
        serde_json::to_string_pretty(&fields)?,
        serde_json::to_string(profile::ADMIN_GROUP)?,
        DISTROS_HELPERS,
    );
    let path = root.join("docs/content/src/distros.ts");
    out.emit(&path, &format_ts(root, &path, &text)?)
}

/// Reads the profile back from an os-release, the way `Profile::from_os_release` does.
const DISTROS_HELPERS: &str = r#"
/** The value of `field` in the text of an /etc/os-release (quotes removed; the last setting wins). */
export function osReleaseValue(osRelease: string, field: string): string | null {
	let found: string | null = null;
	for (const line of osRelease.split("\n")) {
		const trimmed = line.trim();
		if (!trimmed.startsWith(`${field}=`)) continue;
		const value = trimmed.slice(field.length + 1).trim().replace(/^["']|["']$/g, "").trim();
		if (value) found = value;
	}
	return found;
}

/** One profile fact from an os-release; null when it is missing or not a known value. */
export function osReleaseFact<K extends keyof Profile>(osRelease: string, fact: K): Profile[K] | null {
	const value = osReleaseValue(osRelease, OS_RELEASE_FIELDS[fact]);
	const known = PROFILE_VALUES[fact] as readonly string[];
	return value !== null && known.includes(value) ? (value as Profile[K]) : null;
}

/** The variant whose os-release ID is `osId`, if there is one. */
export function distroByOsId(osId: string): Distro | undefined {
	return DISTROS.find((distro) => distro.osId === osId);
}
"#;

/// Packages and the CLIs they build, whose `--help` the docs site shows.
const DOCUMENTED_TOOLS: &[(&str, &[&str])] = &[
    ("recab", &["recab"]),
    ("recinit", &["recinit"]),
    ("reciso", &["reciso"]),
    ("recpart", &["recpart"]),
    ("recstrap", &["recstrap", "recchroot", "recfstab", "recsetup"]),
    ("recuki", &["recuki"]),
];

fn write_tool_help(out: &mut Out, root: &Path) -> Result<()> {
    let mut build = std::process::Command::new("cargo");
    build.current_dir(root).args(["build", "-q"]);
    for (package, _) in DOCUMENTED_TOOLS {
        build.args(["-p", package]);
    }
    if !build.status()?.success() {
        anyhow::bail!("building the documented tools failed");
    }
    let mut text = String::from(
        "// Generated by `cargo xtask gen` from each tool's `--help`. Do not edit.\n\n\
         export const TOOL_HELP = {\n",
    );
    for (_, binaries) in DOCUMENTED_TOOLS {
        for binary in *binaries {
            let target_dir = crate::util::repo::cargo_target_dir(root);
            let output = std::process::Command::new(target_dir.join("debug").join(binary))
                .arg("--help")
                .output()
                .with_context(|| format!("running {binary} --help"))?;
            if !output.status.success() {
                anyhow::bail!("{binary} --help failed");
            }
            let help = String::from_utf8(output.stdout)?;
            text.push_str(&format!("\t{binary}: {},\n", serde_json::to_string(help.trim_end())?));
        }
    }
    text.push_str("} as const\n");
    out.emit(&root.join("docs/content/src/tool-help.ts"), &text)
}

fn write_schema<T: JsonSchema>(out: &mut Out, dir: &Path, name: &str) -> Result<()> {
    let json = serde_json::to_string_pretty(&schema_for!(T))?;
    out.emit(&dir.join(format!("{name}.schema.json")), &(json + "\n"))
}

/// recpart prints its result document on stdout and, on failure, an error document on
/// stderr; this reads either, so callers never look at the streams themselves.
const RECPART_OUTPUT: &str = r#"
/** What a recpart run printed, read the one way recpart writes it. */
export type RecpartOutput<T> =
	| { kind: "ok"; value: T }
	| { kind: "error"; error: ErrorPayload }
	| { kind: "unreadable"; reason: string };

export function readRecpartOutput<T extends { schema_version: number }>(
	run: { exitCode: number | null; stdout: string; stderr: string },
	schemaVersion: number,
): RecpartOutput<T> {
	const ok = run.exitCode === 0;
	const text = ok ? run.stdout : run.stderr;
	let value: { schema_version?: unknown } | null;
	try {
		value = JSON.parse(text);
	} catch {
		return { kind: "unreadable", reason: `recpart printed no JSON (${ok ? "stdout" : "stderr"}): ${text.trim().slice(0, 200)}` };
	}
	const expected = ok ? schemaVersion : ERROR_SCHEMA_VERSION;
	if (!value || value.schema_version !== expected) {
		return { kind: "unreadable", reason: `recpart printed schema ${String(value?.schema_version)}, expected ${expected}` };
	}
	return ok ? { kind: "ok", value: value as T } : { kind: "error", error: value as unknown as ErrorPayload };
}
"#;

const RECSTRAP_OUTPUT: &str = r#"
/** One line of `recstrap --json`; null when the line isn't one. */
export function readStrapEvent(line: string): StrapEvent | null {
	try {
		const value = JSON.parse(line) as { event?: unknown };
		return typeof value?.event === "string" ? (value as StrapEvent) : null;
	} catch {
		return null;
	}
}

/** A failed recstrap or recfstab run's error: the last JSON object on stderr (messages
 * from mount or cp can come before it); null when there is none. */
export function readErrorPayload(stderr: string): ErrorPayload | null {
	const trimmed = stderr.trim();
	const start = trimmed.lastIndexOf("\n{");
	const text = start >= 0 ? trimmed.slice(start + 1) : trimmed.startsWith("{") ? trimmed : "";
	try {
		const value = JSON.parse(text) as Partial<ErrorPayload>;
		return value?.schema_version === ERROR_SCHEMA_VERSION && typeof value.code === "string"
			? (value as ErrorPayload)
			: null;
	} catch {
		return null;
	}
}
"#;

struct Declarations<'a> {
    cfg: &'a Config,
    text: String,
    declared: std::collections::HashSet<std::any::TypeId>,
}

/// Declares a type after everything it refers to, once.
struct Collect<'d, 'a>(&'d mut Declarations<'a>);

impl ts_rs::TypeVisitor for Collect<'_, '_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        self.0.types_from::<T>();
    }
}

impl<'a> Declarations<'a> {
    fn new(cfg: &'a Config) -> Self {
        Self {
            cfg,
            text: HEADER.to_string(),
            declared: Default::default(),
        }
    }

    /// `T` and every type it refers to, dependencies first.
    fn types_from<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_none() || !self.declared.insert(std::any::TypeId::of::<T>()) {
            return;
        }
        T::visit_dependencies(&mut Collect(self));
        self.text.push_str(&format!("\nexport {}\n", T::decl(self.cfg)));
    }

    fn constant<V: Serialize + ?Sized>(&mut self, name: &str, value: &V) -> Result<()> {
        let json = serde_json::to_string(value)?;
        self.text
            .push_str(&format!("\nexport const {name} = {json} as const;\n"));
        Ok(())
    }

    /// The enum's values, and each value's doc comment (its clap help) as `help`.
    fn value_enum<E: clap::ValueEnum + Serialize>(&mut self, values: &str, help: &str) -> Result<()> {
        self.constant(values, E::value_variants())?;
        let mut docs = serde_json::Map::new();
        for variant in E::value_variants() {
            let value = variant.to_possible_value().context("hidden enum value")?;
            let text = value.get_help().map(|h| h.to_string()).unwrap_or_default();
            // Keyed by the serialized name, the one `values` lists (clap's may differ).
            let name = serde_json::to_value(variant)?
                .as_str()
                .context("a unit enum variant serializes as a string")?
                .to_string();
            docs.insert(name, text.into());
        }
        self.constant(help, &docs)
    }

    fn raw(&mut self, text: &str) {
        self.text.push_str(text);
    }

    /// Writes the module as the repo's formatter would leave it, so `gen --check` and
    /// `format:check` agree on the same file.
    fn write(&self, out: &mut Out, root: &Path, path: &Path) -> Result<()> {
        out.emit(path, &format_ts(root, path, &self.text)?)
    }
}

fn format_ts(root: &Path, path: &Path, text: &str) -> Result<String> {
    use std::io::Write;
    let mut child = std::process::Command::new(root.join("node_modules/.bin/oxfmt"))
        .current_dir(root)
        .arg(format!("--stdin-filepath={}", path.display()))
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .spawn()
        .context("running oxfmt (bun install at the repo root)")?;
    child.stdin.take().context("oxfmt stdin")?.write_all(text.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!("oxfmt failed on {}", path.display());
    }
    Ok(String::from_utf8(output.stdout)?)
}
