//! `cargo xtask gen`: the JSON the tools print is described once, by
//! their Rust output types. This writes the JSON Schemas next to each tool
//! and the TypeScript declarations into the TUI that reads that JSON, and
//! captures each tool's `--help` for the docs site, so pages show the real
//! options instead of copies.

use anyhow::{Context, Result, bail};
use schemars::{JsonSchema, schema_for};
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by `cargo xtask gen` from the tool's Rust output types. Do not edit.\n";

/// Where generated text goes: written when it changed, or (with `check`)
/// only compared.
pub struct Out {
    check: bool,
    stale: Vec<PathBuf>,
    written: usize,
}

impl Out {
    fn emit(&mut self, path: &Path, text: &str) -> Result<()> {
        let current = fs::read_to_string(path).ok();
        if current.as_deref() == Some(text) {
            return Ok(());
        }
        if self.check {
            self.stale.push(path.to_path_buf());
            return Ok(());
        }
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(path, text).with_context(|| format!("writing {}", path.display()))?;
        println!("wrote {}", path.display());
        self.written += 1;
        Ok(())
    }
}

pub fn run(check: bool) -> Result<()> {
    let mut out = Out { check, stale: Vec::new(), written: 0 };
    generate(&mut out)?;
    if !out.stale.is_empty() {
        for path in &out.stale {
            eprintln!("out of date: {}", path.display());
        }
        bail!("{} generated file(s) are out of date; run cargo xtask gen", out.stale.len());
    }
    if out.written == 0 {
        println!("generated files are current");
    }
    Ok(())
}

fn generate(out: &mut Out) -> Result<()> {
    let root = crate::util::repo::repo_root()?;

    let schemas = root.join("tools/recpart/docs/frontend-handoff/schemas");
    write_schema::<recpart::DiskListResult>(out, &schemas, "list-disks")?;
    write_schema::<recpart::PartitionPlan>(out, &schemas, "plan-result")?;
    write_schema::<recpart::ApplyResult>(out, &schemas, "apply-result")?;
    write_schema::<recpart::types::ErrorPayload>(out, &schemas, "error")?;
    write_schema::<recab::Status>(out, &root.join("tools/recab/docs"), "status")?;

    let cfg = Config::new().with_large_int("number");
    let mut recpart_ts = Declarations::new(&cfg);
    recpart_ts.types::<recpart::InstallMode>();
    recpart_ts.types::<recpart::DiskTarget>();
    recpart_ts.types::<recpart::DiskInventory>();
    recpart_ts.types::<recpart::DiskListResult>();
    recpart_ts.types::<recpart::LayoutRequest>();
    recpart_ts.types::<recpart::ResolvedLayout>();
    recpart_ts.types::<recpart::types::Filesystem>();
    recpart_ts.types::<recpart::types::PartitionTemplate>();
    recpart_ts.types::<recpart::PartitionPlan>();
    recpart_ts.types::<recpart::types::MountMapping>();
    recpart_ts.types::<recpart::types::ModeContext>();
    recpart_ts.types::<recpart::HandoffPayload>();
    recpart_ts.types::<recpart::types::CommandRecord>();
    recpart_ts.types::<recpart::ApplyResult>();
    recpart_ts.types::<recpart::types::ErrorPayload>();
    recpart_ts.constant("PLAN_SCHEMA_VERSION", &recpart::types::PLAN_SCHEMA_VERSION)?;
    recpart_ts.constant("APPLY_SCHEMA_VERSION", &recpart::types::APPLY_SCHEMA_VERSION)?;
    recpart_ts.constant("HANDOFF_SCHEMA_VERSION", &recpart::types::HANDOFF_SCHEMA_VERSION)?;
    recpart_ts.constant("ERROR_SCHEMA_VERSION", &recpart::types::ERROR_SCHEMA_VERSION)?;
    recpart_ts.constant("DISK_LIST_SCHEMA_VERSION", &recpart::types::DISK_LIST_SCHEMA_VERSION)?;
    recpart_ts.constant("CONFIRM_TOKEN", &recpart::types::CONFIRM_TOKEN)?;
    recpart_ts.constant(
        "INSTALL_MODES",
        <recpart::InstallMode as clap::ValueEnum>::value_variants(),
    )?;
    recpart_ts.write(out, &root.join("tui/apps/install/disk-plan/src/contract/recpart.ts"))?;

    let mut recab_ts = Declarations::new(&cfg);
    recab_ts.types::<recab::Slot>();
    recab_ts.types::<recab::Status>();
    recab_ts.constant("SLOTS", <recab::Slot as clap::ValueEnum>::value_variants())?;
    recab_ts.write(out, &root.join("tui/apps/runtime/recab/src/domain/contract.ts"))?;

    write_tool_help(out, &root)?;
    Ok(())
}

/// Packages and the CLIs they build, whose `--help` the docs site shows.
const DOCUMENTED_TOOLS: &[(&str, &[&str])] = &[
    ("recab", &["recab"]),
    ("recinit", &["recinit"]),
    ("reciso", &["reciso"]),
    ("recpart", &["recpart"]),
    ("recstrap", &["recstrap", "recchroot", "recfstab"]),
    ("recuki", &["recuki"]),
];

fn write_tool_help(out: &mut Out, root: &Path) -> Result<()> {
    let mut build = std::process::Command::new("cargo");
    build.current_dir(root).args(["build", "-q"]);
    for (package, _) in DOCUMENTED_TOOLS {
        build.args(["-p", package]);
    }
    if !build.status()?.success() {
        anyhow::bail!("building the documented tools failed");
    }
    let mut text = String::from(
        "// Generated by `cargo xtask gen` from each tool's `--help`. Do not edit.\n\n\
         export const TOOL_HELP = {\n",
    );
    for (_, binaries) in DOCUMENTED_TOOLS {
        for binary in *binaries {
            let target_dir = std::env::var_os("CARGO_TARGET_DIR")
                .map(std::path::PathBuf::from)
                .unwrap_or_else(|| root.join("target"));
            let output = std::process::Command::new(target_dir.join("debug").join(binary))
                .arg("--help")
                .output()
                .with_context(|| format!("running {binary} --help"))?;
            if !output.status.success() {
                anyhow::bail!("{binary} --help failed");
            }
            let help = String::from_utf8(output.stdout)?;
            text.push_str(&format!("\t{binary}: {},\n", serde_json::to_string(help.trim_end())?));
        }
    }
    text.push_str("} as const\n");
    out.emit(&root.join("docs/content/src/tool-help.ts"), &text)
}

fn write_schema<T: JsonSchema>(out: &mut Out, dir: &Path, name: &str) -> Result<()> {
    let json = serde_json::to_string_pretty(&schema_for!(T))?;
    out.emit(&dir.join(format!("{name}.schema.json")), &(json + "\n"))
}

struct Declarations<'a> {
    cfg: &'a Config,
    text: String,
}

impl<'a> Declarations<'a> {
    fn new(cfg: &'a Config) -> Self {
        Self {
            cfg,
            text: HEADER.to_string(),
        }
    }

    fn types<T: TS>(&mut self) {
        self.text.push_str(&format!("\nexport {}\n", T::decl(self.cfg)));
    }

    fn constant<V: Serialize + ?Sized>(&mut self, name: &str, value: &V) -> Result<()> {
        let json = serde_json::to_string(value)?;
        self.text
            .push_str(&format!("\nexport const {name} = {json} as const;\n"));
        Ok(())
    }

    fn write(&self, out: &mut Out, path: &Path) -> Result<()> {
        out.emit(path, &self.text)
    }
}
